"""Handoff conveniences preserve independently constructed scientific answers."""
from copy import deepcopy
import hashlib
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

from dna_design_core.kernel.public import ToolkitError, require_schema
from tests.fixtures.gen.genome_identity import build

ROOT = Path(__file__).resolve().parents[2]


def operations():
    spec = importlib.util.spec_from_file_location("s1d_identity", ROOT / "kits/genome-identity/capabilities/operations.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class HandoffInputTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="s1d_inputs_")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.case = build(self.root)
        self.module = operations()

    def analyze(self, **updates):
        arguments = {"reference_original": self.case["materials"]["original"],
                     "reference_edited": self.case["materials"]["edited"],
                     "reference_original_file": self.case["paths"]["original"],
                     "reference_edited_file": self.case["paths"]["edited"],
                     "assay_id": "synthetic_identity", "forward_id": "forward", "reverse_id": "reverse",
                     "handoff": self.case["handoff"]}
        return self.module.analyze_assay(None, **{**arguments, **updates})

    def test_handoff_primers_need_no_additional_files(self):
        actual = self.analyze().documents["expected_results"]
        # Literal fixture layout fixes sizes at 1000 and 1300, before Kit execution.
        self.assertEqual(actual, self.case["expected"])

    def test_missing_handoff_or_selected_id_cannot_be_guessed(self):
        for updates in ({"handoff": None}, {"forward_id": "absent"},
                        {"forward": self.case["materials"]["forward"]}):
            with self.subTest(updates=updates), self.assertRaises(ToolkitError):
                self.analyze(**updates)

    def test_explicit_conflicting_primer_is_not_overridden(self):
        with self.assertRaises(ToolkitError):
            self.analyze(forward=self.case["materials"]["reverse"], reverse=self.case["materials"]["reverse"])

    def test_reference_reader_accepts_fasta_and_genbank_without_reexport(self):
        fasta = self.case["paths"]["original"]
        sequence = self.case["materials"]["original"]["sequence"]
        # Hand-written GenBank envelope, not generated by the reader under test.
        genbank = self.root / "reference.gb"
        genbank.write_text("LOCUS       synthetic               1000 bp    DNA     linear   SYN 01-JAN-2000\n"
                           "DEFINITION  Synthetic reference.\nACCESSION   synthetic\nFEATURES             Location/Qualifiers\n"
                           "ORIGIN\n        1 " + sequence.lower() + "\n//\n", encoding="utf-8")
        for path in (fasta, genbank):
            before = path.read_bytes()
            outcome = self.module.read_reference(None, path, topology="linear")
            self.assertEqual(outcome.products["material"], self.case["materials"]["original"])
            self.assertEqual(path.read_bytes(), before)

    def test_genbank_hashes_are_actual_file_bytes(self):
        references, handoff, expected = {}, deepcopy(self.case["handoff"]), deepcopy(self.case["expected"])
        for role in ("original", "edited"):
            sequence = self.case["materials"][role]["sequence"]
            path = self.root / (role + ".gb")
            path.write_text(f"LOCUS       synthetic               {len(sequence)} bp    DNA     linear   SYN 01-JAN-2000\n"
                            "DEFINITION  Synthetic.\nACCESSION   synthetic\nFEATURES             Location/Qualifiers\n"
                            "ORIGIN\n        1 " + sequence.lower() + "\n//\n", encoding="utf-8")
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            next(row for row in handoff["references"] if row["role"] == role)["sha256"] = digest
            next(row for row in expected["backgrounds"] if row["id"] == role)["reference_sha256"] = digest
            references["reference_" + role + "_file"] = path
        self.assertEqual(self.analyze(**references, handoff=handoff).documents["expected_results"], expected)

    def test_reference_reader_rejects_conflicting_topology_and_unknown_extension(self):
        path = self.root / "not-a-supported-format.txt"
        path.write_bytes(self.case["paths"]["original"].read_bytes())
        with self.assertRaises(ToolkitError):
            self.module.read_reference(None, path, topology="linear")
        genbank = self.root / "circular.gb"
        genbank.write_text("LOCUS       synthetic                 20 bp    DNA     circular SYN 01-JAN-2000\n"
                           "DEFINITION  Synthetic.\nACCESSION   synthetic\nFEATURES             Location/Qualifiers\n"
                           "ORIGIN\n        1 acgtacgtacgtacgtacgt\n//\n", encoding="utf-8")
        with self.assertRaises(ToolkitError):
            self.module.read_reference(None, genbank, topology="linear")

    def test_new_export_matches_decorator(self):
        declaration = self.module.read_reference.declaration
        require_schema("capability-v1", declaration)
        exported = json.loads((ROOT / "kits/genome-identity/capabilities/read_reference.json").read_text(encoding="utf-8"))
        self.assertEqual(exported, declaration)


if __name__ == "__main__":
    unittest.main()
